// Generates src/strudel.sounds.generated.d.ts: union types for autocomplete of
//   SoundName   — built-in synths + every sample name main.ts loads (drum-machine parts as "bd", "sd", ...)
//   BankName    — drum machine banks for .bank()
//   ScaleName / ScaleString — tonal scale names, and "Root:scale" strings for .scale()
//
// Sample maps are fetched from https://strudel.b-cdn.net/<name>.json and cached in
// node_modules/.cache/strudel-samples (same cache as scripts/check-songs.mjs).
//
// Usage: node scripts/gen-sound-types.mjs [--offline]

import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { ScaleType } from "@tonaljs/tonal";
import * as webaudio from "@strudel/webaudio";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cacheDir = join(root, "node_modules/.cache/strudel-samples");
const outFile = join(root, "src/strudel.sounds.generated.d.ts");
const offline = process.argv.includes("--offline");

// Keep in sync with SAMPLE_MAPS / BANK_ALIASES in src/main.ts
const SAMPLE_MAPS = ["tidal-drum-machines", "piano", "vcsl", "uzu-drumkit", "uzu-wavetables", "mridangam"];
const DRUM_MACHINES = "tidal-drum-machines";
// main.ts applies this with aliasBank() after the banks load, so "TR909" works like "RolandTR909"
const BANK_ALIASES = "tidal-drum-machines-alias";

async function loadJson(name) {
  const file = join(cacheDir, `${name}.json`);
  if (existsSync(file)) return JSON.parse(readFileSync(file, "utf8"));
  if (offline) throw new Error(`${name}.json not cached (run without --offline)`);
  const res = await fetch(`https://strudel.b-cdn.net/${name}.json`);
  if (!res.ok) throw new Error(`fetch ${name}: ${res.status}`);
  const json = await res.json();
  mkdirSync(cacheDir, { recursive: true });
  writeFileSync(file, JSON.stringify(json));
  return json;
}

// Built-in synths: ask superdough itself (works without an AudioContext)
webaudio.registerSynthSounds();
webaudio.registerZZFXSounds();
const synths = Object.keys(webaudio.soundMap.get());

const samples = new Set();
const parts = new Set();
const banks = new Set();
for (const name of SAMPLE_MAPS) {
  const map = await loadJson(name);
  for (const key of Object.keys(map)) {
    if (key === "_base") continue;
    if (name === DRUM_MACHINES) {
      const i = key.indexOf("_");
      if (i <= 0 || i === key.length - 1) continue; // e.g. a stray "OberheimDMX_" key
      banks.add(key.slice(0, i));
      parts.add(key.slice(i + 1));
    } else {
      samples.add(key);
    }
  }
}

const aliasMap = await loadJson(BANK_ALIASES);
const bankAliases = new Set();
for (const [bank, alias] of Object.entries(aliasMap)) {
  if (!banks.has(bank)) continue;
  for (const a of [alias].flat()) bankAliases.add(a);
}

const sortU = (xs) => [...new Set(xs)].sort((a, b) => a.localeCompare(b));
const union = (xs, indent = "  ") => xs.map((x) => `${indent}| ${JSON.stringify(x)}`).join("\n");

// Scales: tonal names + aliases, written the way mini-notation needs them ("major:pentatonic").
// Names with characters mini-notation would split on (#, ', -, digits after space are fine) are skipped.
const scaleNames = sortU(
  ScaleType.all()
    .flatMap((s) => [s.name, ...s.aliases])
    .filter((n) => /^[a-z0-9 ]+$/.test(n))
    .map((n) => n.replace(/ /g, ":")),
);
const ROOTS = ["C", "C#", "Db", "D", "D#", "Eb", "E", "F", "F#", "Gb", "G", "G#", "Ab", "A", "A#", "Bb", "B"];

const body = `// ════════════════════════════════════════════════════════════════════════════
// AUTO-GENERATED by scripts/gen-sound-types.mjs — do not edit by hand.
// Sounds from the sample maps src/main.ts loads + superdough's built-in synths,
// and scale names from tonal. Used for autocomplete in s()/sound()/.bank()/.scale();
// the signatures still accept any string (mini-notation like "bd*2 [sd hh]").
// ════════════════════════════════════════════════════════════════════════════

/** Built-in synths and noise generators (superdough). */
type SynthName =
${union(sortU(synths))};

/** Drum sounds of the drum machine banks (not every bank has every part) — combine with \`.bank()\`, e.g. \`s("bd sd").bank("RolandTR909")\`. */
type DrumPartName =
${union(sortU(parts))};

/** Sample names from ${SAMPLE_MAPS.filter((m) => m !== DRUM_MACHINES).join(", ")}. */
type SampleName =
${union(sortU(samples))};

/** Every sound name s()/sound() can play (drum machine sounds need \`.bank()\`). */
type SoundName = SynthName | DrumPartName | SampleName;

/** Drum machine banks (${DRUM_MACHINES}) for \`.bank()\`, e.g. "RolandTR909". */
type DrumMachineBankName =
${union(sortU(banks))};

/** Short bank aliases from ${BANK_ALIASES} (registered with aliasBank() in main.ts), e.g. "TR909". */
type BankAliasName =
${union(sortU(bankAliases))};

/** Every bank name \`.bank()\` accepts. */
type BankName = DrumMachineBankName | BankAliasName;

/** Scale types understood by .scale() — multi-word scales use ":" (e.g. "major:pentatonic"). */
type ScaleName =
${union(scaleNames)};

/** Scale roots (an octave may follow, e.g. "C4:minor"; defaults to octave 3). */
type ScaleRoot = ${ROOTS.map((r) => JSON.stringify(r)).join(" | ")};

/** A scale string for .scale(), e.g. "C:minor", "F#:dorian", "A:minor:pentatonic". */
type ScaleString = \`\${ScaleRoot}:\${ScaleName}\`;
`;

writeFileSync(outFile, body);
console.log(
  `wrote ${outFile.replace(root + "/", "")}: ${synths.length} synths, ${parts.size} drum parts, ${samples.size} samples, ${banks.size} banks (+${bankAliases.size} aliases), ${scaleNames.length} scales`,
);
